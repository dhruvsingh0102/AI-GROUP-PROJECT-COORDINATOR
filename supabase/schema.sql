-- Coordinator database schema. Run in the Supabase SQL Editor once per project.
-- Access is intended only from trusted server code using SUPABASE_SECRET_KEY.
create table if not exists public.people (
  id bigint generated by default as identity primary key,
  name text not null,
  name_normalized text not null unique,
  whatsapp_phone text unique,
  whatsapp_last_inbound_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  assignee_id bigint references public.people(id) on delete set null,
  unblocker_id bigint references public.people(id) on delete set null,
  status text not null default 'Pending' check (status in ('Pending', 'In Progress', 'Blocked', 'Needs Clarification', 'Complete')),
  blocker text,
  updated_at timestamptz not null default now()
);

create table if not exists public.updates (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  person_id bigint references public.people(id) on delete set null,
  message text not null,
  status text not null,
  blocker text,
  created_at timestamptz not null default now()
);

create table if not exists public.followups (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  recipient_id bigint not null references public.people(id) on delete cascade,
  message text not null,
  sent_at timestamptz not null default now()
);

create table if not exists public.processed_whatsapp_messages (
  message_id text primary key,
  received_at timestamptz not null default now()
);

create index if not exists tasks_status_idx on public.tasks(status);
create index if not exists updates_task_idx on public.updates(task_id);
create index if not exists followups_task_idx on public.followups(task_id);

create or replace function public.set_task_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
drop trigger if exists tasks_set_updated_at on public.tasks;
create trigger tasks_set_updated_at before update on public.tasks
for each row execute function public.set_task_updated_at();

alter table public.people enable row level security;
alter table public.tasks enable row level security;
alter table public.updates enable row level security;
alter table public.followups enable row level security;
alter table public.processed_whatsapp_messages enable row level security;

grant usage on schema public to service_role;
grant all on public.people, public.tasks, public.updates, public.followups to service_role;
grant all on public.processed_whatsapp_messages to service_role;
grant usage, select on all sequences in schema public to service_role;
